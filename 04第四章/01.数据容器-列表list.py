"""
列表是数据容器中的一类,一次性可以存储多个数据(元素)
定义: 列表名称 = [元素1,元素2,元素3,...]
特点:
    1.可以存储不同类型的元素
    2.元素有序,可重复,可修改
    3.正向索引:从0开始;反向索引:从后往前(-1开始)
    4.容器中的元素按特定顺序排列的,可通过索引访问的容器类型称之为序列
删除:
    删除列表的元素:del s[x]
"""

s = [56 , 90, 60, "a", "HELLO", True]
print(type(s))

print(s[0])
print(s[-1])

s[4] = "B"
print(s[4])
print(s)

#删除
del s [4]
print(s)

# 通过for循环遍历列表的元素
for i in s:
    print(i)