# 赋值运算符: = += -= *= /= %= //= **=
num = 85
num += 10
print(f"num += 10 ,num = {num}")
num -= 10
print(f"num -= 10 ,num = {num}")
num *= 10
print(f"num *= 10 ,num = {num}")
num /= 10
print(f"num /= 10 ,num = {num}")
num //= 10
print(f"num //= 10 ,num = {num}")
num %= 3
print(f"num %= 3 ,num = {num}")
num **= 3
print(f"num **= 3 ,num = {num}")