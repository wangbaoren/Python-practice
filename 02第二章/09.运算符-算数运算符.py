# 算数运算符: + - * / //整除  %取余  **幂指数
print("10+4=",10+4)
print("10-4=",10-4)
print("10*4=",10*4)
print("10/4=",10/4)
print("10//4=",10//4)
print("10%4=",10%4)
print("10**4=",10**4)

# 算术运算符的优先级: ** --> * / // % --> + -
print(" 0.1 + 10 / 4**2 = ",0.1 + 10 / 4**2)

# 案例: 输入x和y ,输出 x+y和x-y的值
# 因为计算机底层是基于二进制来进行数据的存储和处理的,而二进制无法精确表示所有的小数,因此涉及到浮点数运算会出现损失精度
x = float(input("请输入x的值:"))
y = float(input("请输入y的值:"))
print(f"x+y的值为{x+y},x-y的值为{x-y}")