# 比较运算符:   1. 等于    ==
#             2. 不等于  !=
#             3. 大于    >
#             4.大于等于  >=
#             5.小于     <
#             6.小于等于  <=
print("100 == 100 吗:",100 == 100)
print("100 != 100 吗:",100 != 100)
print("100 > 100 吗:",100 > 100)
print("100 >= 100 吗:",100 >= 100)
print("100 < 100 吗:",100 < 100)
print("100 <= 100 吗:",100 <= 100)